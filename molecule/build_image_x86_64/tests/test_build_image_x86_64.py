@pytest.mark.parametrize("container", S3_CONTAINERS)
def test_s3_container_running(host, container):
    """Verify S3 containers are running without any errors."""
    log = TestLogger(TEST_NAMES["s3_container_running"].format(container=container))
    log.check(f"Checking S3 container: {container}")

    result = check_s3_container_running(host, container)

    if result["success"]:
        log.passed(LOG_MSGS["s3_container_running"].format(container=container), result["status"])
    else:
        log.failed(LOG_MSGS["s3_container_not_running"].format(container=container), result["error"])

    assert result["success"], ASSERT_MSGS["s3_container_not_running"].format(
        container=container, status=result["status"]
    )


