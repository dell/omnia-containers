def test_all_functional_group_images_in_s3(host):
    """Verify all 3 images for each functional group are in S3 bucket."""
    log = TestLogger("Verify all functional group images in S3")
    bucket = TEST_VARS["s3_bucket"]

    # Get functional groups
    groups = get_functional_groups(host)
    log.check(f"Found {len(groups)} functional groups to verify")

    if not groups:
        log.failed("No functional groups found", "functional_group.yml may be empty or invalid")
        pytest.skip("No functional groups found in functional_group.yml")

    all_passed = True
    failed_groups = []

    for group in groups:
        result = check_functional_group_images_in_s3(host, group)
        if result["success"]:
            log.passed(
                LOG_MSGS["functional_group_images_ok"].format(group=group),
                f"Found: {', '.join(result['found'])}"
            )
        else:
            all_passed = False
            failed_groups.append({
                "group": group,
                "missing": result["missing"]
            })
            log.failed(
                LOG_MSGS["functional_group_images_missing"].format(
                    group=group, missing=", ".join(result["missing"])
                ),
                result["error"]
            )

    if not all_passed:
        failed_details = "\n".join([
            f"║   - {fg['group']}: missing {', '.join(fg['missing'])}"
            for fg in failed_groups
        ])
        assert False, (
            f"╔══════════════════════════════════════════════════════════════════════════════╗\n"
            f"║ FUNCTIONAL GROUP IMAGES MISSING IN S3\n"
            f"╠══════════════════════════════════════════════════════════════════════════════╣\n"
            f"║ Bucket: {bucket}\n"
            f"║ Failed Groups:\n"
            f"{failed_details}\n"
            f"║\n"
            f"║ HOW TO FIX:\n"
            f"║   1. List S3 contents: s3cmd ls -Hr s3://boot-images\n"
            f"║   2. Check build logs for errors\n"
            f"║   3. Re-run build_image_x86_64.yml to push images\n"
            f"╚══════════════════════════════════════════════════════════════════════════════╝"
        )
