def check_coredhcp_file_exists(host) -> Dict[str, Any]:
    """
    Check if /etc/openchami/configs/coredhcp.yaml exists on the OIM host.

    This file is generated by prepare_oim.yml on the OIM host (outside container).

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, path, content (if exists), error
    """
    cmd = host.run(f"cat {COREDHCP_CONFIG_PATH} 2>/dev/null")
    if cmd.rc == 0 and cmd.stdout.strip():
        return {
            "success": True,
            "path": COREDHCP_CONFIG_PATH,
            "content": cmd.stdout,
            "error": "",
        }

    return {
        "success": False,
        "path": COREDHCP_CONFIG_PATH,
        "content": "",
        "error": f"File not found or empty: {COREDHCP_CONFIG_PATH}",
    }


def check_coredhcp_multisubnet_mode(host) -> Dict[str, Any]:
    """
    Check whether coredhcp.yaml is in multi-subnet mode.

    Detects three possible states:
    - 'multi-subnet': key=value coresmd format is active (uncommented).
      This means coresmd v0.6.0+ was available when prepare_oim ran.
    - 'commented': multi-subnet entries exist but are commented out.
      This means prepare_oim detected additional_subnets but coresmd
      was < v0.6.0 at template render time. The 6-step manual
      activation instructions are present in the file.
    - 'single-subnet': positional coresmd format only, no multi-subnet
      entries at all (neither active nor commented).

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, mode, details, error
    """
    file_result = check_coredhcp_file_exists(host)
    if not file_result["success"]:
        return {
            "success": False,
            "mode": "unknown",
            "details": "",
            "error": file_result["error"],
        }

    content = file_result["content"]

    # Scan for active and commented multi-subnet markers
    active_coresmd = False
    active_bootloop = False
    commented_coresmd = False
    commented_bootloop = False

    for line in content.split("\n"):
        stripped = line.strip()
        if stripped.startswith("#"):
            uncommented = stripped.lstrip("# ")
            if MULTISUBNET_CORESMD_MARKER in uncommented:
                commented_coresmd = True
            if MULTISUBNET_BOOTLOOP_MARKER in uncommented:
                commented_bootloop = True
        else:
            if MULTISUBNET_CORESMD_MARKER in stripped:
                active_coresmd = True
            if MULTISUBNET_BOOTLOOP_MARKER in stripped:
                active_bootloop = True

    # State 1: Active multi-subnet mode
    if active_coresmd and active_bootloop:
        return {
            "success": True,
            "mode": "multi-subnet",
            "details": (
                "coresmd plugin uses key=value format (svc_base_uri=...)\n"
                "bootloop plugin uses subnet_pool= directives"
            ),
            "error": "",
        }

    # State 2: Multi-subnet entries present but commented out
    if commented_coresmd and commented_bootloop:
        return {
            "success": True,
            "mode": "commented",
            "details": (
                "Multi-subnet entries are present in coredhcp.yaml "
                "but commented out (6-step manual activation required).\n"
                "This is expected when coresmd was < v0.6.0 at "
                "prepare_oim time but additional_subnets are configured."
            ),
            "error": "",
        }

    # Partial state (only one of the two markers found)
    if active_coresmd or active_bootloop:
        return {
            "success": False,
            "mode": "partial",
            "details": (
                f"Partial multi-subnet config detected. "
                f"coresmd key=value: {active_coresmd}, "
                f"bootloop subnet_pool: {active_bootloop}"
            ),
            "error": "Incomplete multi-subnet transformation",
        }

    return {
        "success": False,
        "mode": "single-subnet",
        "details": "coresmd uses positional argument format (single-subnet)",
        "error": "CoreDHCP is in single-subnet mode",
    }


def verify_subnet_entries_in_coredhcp(host) -> Dict[str, Any]:
    """
    Verify that all additional_subnets from network_spec.yml have corresponding
    entries in coredhcp.yaml.

    For each additional subnet, checks:
    - coresmd rule with subnet:CIDR,type:Node,routers:ROUTER
    - coresmd rule with subnet:CIDR,type:NodeBMC,routers:ROUTER
    - bootloop subnet_pool with CIDR,start_ip,end_ip

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, subnets (list of per-subnet results),
        missing_count, total, error
    """
    additional = get_additional_subnets(host)
    if not additional:
        return {
            "success": True,
            "subnets": [],
            "missing_count": 0,
            "total": 0,
            "error": "",
        }

    file_result = check_coredhcp_file_exists(host)
    if not file_result["success"]:
        return {
            "success": False,
            "subnets": [],
            "missing_count": len(additional),
            "total": len(additional),
            "error": file_result["error"],
        }

    content = file_result["content"]

    # Build both active and full (including commented) content for matching
    active_lines = []
    all_lines = []
    for line in content.split("\n"):
        stripped = line.strip()
        all_lines.append(stripped)
        if not stripped.startswith("#"):
            active_lines.append(stripped)
        else:
            # Strip comment prefix for matching commented entries
            all_lines.append(stripped.lstrip("# "))

    active_content = "\n".join(active_lines)
    all_content = "\n".join(all_lines)

    subnet_results = []
    missing_count = 0

    for subnet_cfg in additional:
        subnet = subnet_cfg.get("subnet", "")
        netmask = subnet_cfg.get("netmask_bits", "")
        router = subnet_cfg.get("router", "")
        dynamic_range = subnet_cfg.get("dynamic_range", "")
        cidr = f"{subnet}/{netmask}"

        # Expected entries
        node_rule = f"subnet:{cidr},type:Node,routers:{router},cidr:{netmask}"
        bmc_rule = f"subnet:{cidr},type:NodeBMC,routers:{router},cidr:{netmask}"

        # Parse dynamic range for bootloop
        range_parts = dynamic_range.split("-") if dynamic_range else []
        if len(range_parts) == 2:
            pool_entry = f"subnet_pool={cidr},{range_parts[0]},{range_parts[1]}"
        else:
            pool_entry = f"subnet_pool={cidr}"

        # Check active lines first, then fall back to all lines (commented)
        node_active = node_rule in active_content
        bmc_active = bmc_rule in active_content
        pool_active = pool_entry in active_content

        node_commented = node_rule in all_content
        bmc_commented = bmc_rule in all_content
        pool_commented = pool_entry in all_content

        # "found" = present in either active or commented form
        has_node_rule = node_active or node_commented
        has_bmc_rule = bmc_active or bmc_commented
        has_pool = pool_active or pool_commented

        all_found = has_node_rule and has_bmc_rule and has_pool
        if not all_found:
            missing_count += 1

        # Determine state per entry
        if node_active and bmc_active and pool_active:
            entry_state = "active"
        elif all_found:
            entry_state = "commented"
        else:
            entry_state = "missing"

        subnet_results.append({
            "subnet": cidr,
            "router": router,
            "dynamic_range": dynamic_range,
            "success": all_found,
            "state": entry_state,
            "node_rule_found": has_node_rule,
            "node_rule_active": node_active,
            "bmc_rule_found": has_bmc_rule,
            "bmc_rule_active": bmc_active,
            "pool_found": has_pool,
            "pool_active": pool_active,
            "expected_node_rule": f"rule={node_rule}",
            "expected_bmc_rule": f"rule={bmc_rule}",
            "expected_pool": pool_entry,
        })

    return {
        "success": missing_count == 0,
        "subnets": subnet_results,
        "missing_count": missing_count,
        "total": len(additional),
        "error": (
            f"{missing_count}/{len(additional)} subnet entries missing"
            if missing_count > 0 else ""
        ),
    }


