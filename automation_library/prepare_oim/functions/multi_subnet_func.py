def _get_admin_network(host) -> Dict[str, str]:
    """
    Get primary admin_network config from network_spec.yml.

    Returns:
        Dict with subnet, netmask_bits, primary_oim_admin_ip keys.
        Empty dict on failure.
    """
    config = load_input_file(host, NETWORK_SPEC_FILE)
    networks = config.get("Networks", config.get("networks", []))
    for network in networks:
        if isinstance(network, dict):
            admin = network.get("admin_network", {})
            if admin:
                return admin
    return {}


