# NODE-TO-SUBNET MAPPING VERIFICATION
# =============================================================================

def verify_node_subnet_mapping(host) -> Dict[str, Any]:
    """
    Verify that every node in PXE mapping has its ADMIN_IP within either the
    primary admin subnet or one of the additional_subnets.

    This is multi-subnet specific: it confirms that each provisioned node
    belongs to a known subnet that CoreDHCP is configured to serve.

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, total, matched, unmatched, subnet_map (per-subnet
        node list), node_results (per-node detail), error
    """
    # Build list of all known subnets (primary + additional)
    admin_net = _get_admin_network(host)
    if not admin_net:
        return {
            "success": False, "total": 0, "matched": 0, "unmatched": 0,
            "subnet_map": {}, "node_results": [],
            "error": "Could not read admin_network from network_spec.yml",
        }

    subnets = []
    primary_subnet = admin_net.get("subnet", "")
    primary_bits = admin_net.get("netmask_bits", "24")
    if primary_subnet:
        cidr = f"{primary_subnet}/{primary_bits}"
        subnets.append({
            "cidr": cidr,
            "network": ipaddress.ip_network(cidr, strict=False),
            "label": f"{cidr} (primary)",
        })

    for sub in get_additional_subnets(host):
        sub_addr = sub.get("subnet", "")
        sub_bits = sub.get("netmask_bits", "24")
        if sub_addr:
            cidr = f"{sub_addr}/{sub_bits}"
            subnets.append({
                "cidr": cidr,
                "network": ipaddress.ip_network(cidr, strict=False),
                "label": cidr,
            })

    if not subnets:
        return {
            "success": False, "total": 0, "matched": 0, "unmatched": 0,
            "subnet_map": {}, "node_results": [],
            "error": "No subnets found in network_spec.yml",
        }

    # Get all nodes from PXE mapping
    all_fg = get_functional_groups_from_pxe_mapping(host)
    all_nodes = []
    for fg in all_fg:
        nodes = get_nodes_info(host, search_by="functional_group",
                               search_value=fg)
        all_nodes.extend(nodes)

    if not all_nodes:
        return {
            "success": False, "total": 0, "matched": 0, "unmatched": 0,
            "subnet_map": {}, "node_results": [],
            "error": "No nodes found in PXE mapping",
        }

    # Classify each node into a subnet
    subnet_map = {s["label"]: [] for s in subnets}
    node_results = []
    unmatched = 0

    for node in all_nodes:
        admin_ip = node.get("admin_ip", "")
        hostname = node.get("hostname", "")
        fg = node.get("functional_group", "")

        if not admin_ip:
            node_results.append({
                "hostname": hostname, "functional_group": fg,
                "admin_ip": "", "subnet": None, "matched": False,
                "reason": "No ADMIN_IP",
            })
            unmatched += 1
            continue

        try:
            ip_obj = ipaddress.ip_address(admin_ip)
        except ValueError:
            node_results.append({
                "hostname": hostname, "functional_group": fg,
                "admin_ip": admin_ip, "subnet": None, "matched": False,
                "reason": f"Invalid IP: {admin_ip}",
            })
            unmatched += 1
            continue

        matched_subnet = None
        for sub in subnets:
            if ip_obj in sub["network"]:
                matched_subnet = sub["label"]
                subnet_map[matched_subnet].append(hostname)
                break

        if matched_subnet:
            node_results.append({
                "hostname": hostname, "functional_group": fg,
                "admin_ip": admin_ip, "subnet": matched_subnet,
                "matched": True, "reason": "",
            })
        else:
            node_results.append({
                "hostname": hostname, "functional_group": fg,
                "admin_ip": admin_ip, "subnet": None, "matched": False,
                "reason": f"{admin_ip} not in any configured subnet",
            })
            unmatched += 1

    return {
        "success": unmatched == 0,
        "total": len(all_nodes),
        "matched": len(all_nodes) - unmatched,
        "unmatched": unmatched,
        "subnet_map": subnet_map,
        "node_results": node_results,
        "error": (
            f"{unmatched} node(s) not in any configured subnet"
            if unmatched > 0 else ""
        ),
    }


# =============================================================================
# CROSS-SUBNET SSH REACHABILITY VERIFICATION
# =============================================================================

def verify_cross_subnet_ssh(host) -> Dict[str, Any]:
    """
    Verify SSH reachability from OIM to at least one node per additional subnet.

    Picks one representative node from each additional subnet (based on PXE
    mapping ADMIN_IP classification) and runs an SSH connectivity check from
    omnia_core container.

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, subnet_results (per-subnet detail), error
    """
    # First get the node-to-subnet mapping
    mapping = verify_node_subnet_mapping(host)
    if not mapping["success"] and not mapping.get("subnet_map"):
        return {
            "success": False,
            "subnet_results": [],
            "error": mapping.get("error", "Could not determine subnet mapping"),
        }

    additional = get_additional_subnets(host)
    if not additional:
        return {
            "success": True,
            "subnet_results": [],
            "error": "",
        }

    # Build set of additional subnet CIDRs
    additional_cidrs = set()
    for sub in additional:
        sub_addr = sub.get("subnet", "")
        sub_bits = sub.get("netmask_bits", "24")
        if sub_addr:
            additional_cidrs.add(f"{sub_addr}/{sub_bits}")

    # For each additional subnet, pick a representative node and SSH to it
    subnet_results = []
    all_ok = True

    for nr in mapping.get("node_results", []):
        if not nr.get("matched") or not nr.get("subnet"):
            continue

        # Check if this node's subnet is an additional subnet
        subnet_label = nr["subnet"]
        # subnet_label is either "cidr (primary)" or just "cidr"
        subnet_cidr = subnet_label.replace(" (primary)", "")
        if subnet_cidr not in additional_cidrs:
            continue

        # Check if we already tested this subnet
        already_tested = any(
            sr["subnet"] == subnet_label for sr in subnet_results
        )
        if already_tested:
            continue

        # SSH from omnia_core to this node
        admin_ip = nr["admin_ip"]
        hostname = nr["hostname"]
        ssh_cmd = (
            f"podman exec omnia_core "
            f"ssh -o StrictHostKeyChecking=no -o ConnectTimeout=10 "
            f"root@{admin_ip} 'hostname'"
        )
        result = host.run(ssh_cmd)
        ssh_ok = result.rc == 0

        subnet_results.append({
            "subnet": subnet_label,
            "test_node": hostname,
            "test_ip": admin_ip,
            "ssh_success": ssh_ok,
            "output": result.stdout.strip() if ssh_ok
                      else result.stderr.strip(),
        })

        if not ssh_ok:
            all_ok = False

    # Log additional subnets that had no nodes (informational, not a failure)
    tested_cidrs = set()
    for sr in subnet_results:
        tested_cidrs.add(sr["subnet"].replace(" (primary)", ""))

    for cidr in additional_cidrs:
        if cidr not in tested_cidrs:
            subnet_results.append({
                "subnet": cidr,
                "test_node": None,
                "test_ip": None,
                "ssh_success": True,
                "output": "No nodes in PXE mapping — skipped",
            })

    return {
        "success": all_ok,
        "subnet_results": subnet_results,
        "error": "" if all_ok else "SSH failed for one or more subnets",
    }


# =============================================================================
# CORESMD RUNNING CONTAINER IMAGE VERIFICATION
# =============================================================================

def verify_coresmd_running_image(host) -> Dict[str, Any]:
    """
    Verify that the running coresmd-coredhcp and coresmd-coredns containers
    are using the expected multi-subnet image version.

    This goes beyond checking the quadlet file — it inspects the actual
    running container image to confirm the restart was effective.

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, container_results (per-container detail), error
    """
    container_results = []
    all_ok = True

    for container_name in ("coresmd-coredhcp", "coresmd-coredns"):
        # Get the image of the running container
        inspect_cmd = host.run(
            f"podman inspect {container_name} "
            f"--format '{{{{.ImageName}}}}'"
        )

        if inspect_cmd.rc != 0:
            container_results.append({
                "container": container_name,
                "running": False,
                "actual_image": "",
                "expected_image": CORESMD_MULTISUBNET_IMAGE,
                "match": False,
                "error": f"Container not running or inspect failed: "
                         f"{inspect_cmd.stderr.strip()}",
            })
            all_ok = False
            continue

        actual_image = inspect_cmd.stdout.strip()
        match = actual_image == CORESMD_MULTISUBNET_IMAGE

        container_results.append({
            "container": container_name,
            "running": True,
            "actual_image": actual_image,
            "expected_image": CORESMD_MULTISUBNET_IMAGE,
            "match": match,
            "error": "" if match else (
                f"Expected {CORESMD_MULTISUBNET_IMAGE}, "
                f"got {actual_image}"
            ),
        })

        if not match:
            all_ok = False

    return {
        "success": all_ok,
        "container_results": container_results,
        "error": "" if all_ok else "One or more containers using wrong image",
    }
