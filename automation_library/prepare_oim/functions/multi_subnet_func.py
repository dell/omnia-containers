def get_additional_subnets(host) -> List[Dict[str, str]]:
    """
    Get the additional_subnets list from network_spec.yml.

    Reads the Networks[0].admin_network.additional_subnets field.

    Args:
        host: Testinfra host object

    Returns:
        List of subnet dicts with keys: subnet, netmask_bits, router, dynamic_range.
        Returns empty list if not configured.
    """
    config = load_input_file(host, NETWORK_SPEC_FILE)
    networks = config.get("Networks", config.get("networks", []))
    for network in networks:
        if isinstance(network, dict):
            admin = network.get("admin_network", {})
            if admin:
                subnets = admin.get("additional_subnets", [])
                if subnets and isinstance(subnets, list):
                    return subnets
    return []


def has_additional_subnets(host) -> bool:
    """
    Check if additional_subnets are configured in network_spec.yml.

    Args:
        host: Testinfra host object

    Returns:
        True if additional_subnets list is non-empty
    """
    return len(get_additional_subnets(host)) > 0


