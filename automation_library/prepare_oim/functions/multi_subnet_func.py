# COREDHCP MULTI-SUBNET ACTIVATION (6-STEP PROCESS)
# =============================================================================

def activate_multisubnet_coredhcp(host) -> Dict[str, Any]:
    """
    Activate multi-subnet CoreDHCP configuration on the OIM host.

    Performs the 6-step process documented in coredhcp.yaml comments:
      1. Pull the coresmd v0.6.3 image (podman pull)
      2. Comment out the single-subnet coresmd and bootloop lines
      3. Uncomment the multi-subnet coresmd and bootloop blocks
      4. Update the coresmd image version in quadlet container files
      5. Reload systemd daemon (systemctl daemon-reload)
      6. Restart openchami.target (systemctl restart openchami.target)

    This function is idempotent — if multi-subnet mode is already active,
    it returns success without making changes.

    Args:
        host: Testinfra host object

    Returns:
        Dict with success, steps (list of step results), error
    """
    steps = []

    # Pre-check: is multi-subnet already active?
    mode_result = check_coredhcp_multisubnet_mode(host)
    if mode_result.get("mode") == "multi-subnet":
        # Also verify quadlet images are at the correct version
        quadlet_ok = True
        for qf in (CORESMD_COREDHCP_CONTAINER_FILE,
                    CORESMD_COREDNS_CONTAINER_FILE):
            chk = host.run(
                f"grep -q 'Image={CORESMD_MULTISUBNET_IMAGE}' {qf}"
            )
            if chk.rc != 0:
                quadlet_ok = False
                break
        if quadlet_ok:
            return {
                "success": True,
                "steps": [{"step": 0, "name": "pre-check",
                            "detail": "Already in multi-subnet mode"}],
                "error": "",
            }
        # Multi-subnet config is active but quadlet images need updating
        # Skip to step 1 (pull) + step 4-6 only
        steps = [{"step": 0, "name": "pre-check", "success": True,
                  "detail": "Config is multi-subnet but quadlet images "
                            "need updating"}]
        skip_config_edit = True
    else:
        skip_config_edit = False

    # Verify coredhcp.yaml exists and has commented multi-subnet entries
    if not skip_config_edit:
        if mode_result.get("mode") not in ("commented", "single-subnet"):
            if not mode_result["success"]:
                return {
                    "success": False,
                    "steps": [],
                    "error": mode_result.get("error",
                                             "Cannot determine config mode"),
                }

    # ── Step 1: Pull coresmd image ──────────────────────────────────────
    pull_cmd = host.run(f"podman pull {CORESMD_MULTISUBNET_IMAGE}")
    step1_ok = pull_cmd.rc == 0
    steps.append({
        "step": 1,
        "name": "Pull coresmd image",
        "command": f"podman pull {CORESMD_MULTISUBNET_IMAGE}",
        "success": step1_ok,
        "detail": pull_cmd.stdout.strip() if step1_ok else pull_cmd.stderr.strip(),
    })
    if not step1_ok:
        return {
            "success": False,
            "steps": steps,
            "error": f"Step 1 failed: podman pull {CORESMD_MULTISUBNET_IMAGE}",
        }

    if not skip_config_edit:
        # ── Step 2: Comment out single-subnet coresmd and bootloop lines ─
        # Uses sed to find the two active lines after the single-subnet
        # comment and prepend them with '# '
        sed_comment = (
            f"sed -i '/{SINGLE_SUBNET_CORESMD_COMMENT.replace('/', '\\\\/')}/"
            "{n;s/^\\(    - coresmd:.*\\)/    # \\1/;n;"
            "s/^\\(    - bootloop:.*\\)/    # \\1/}' "
            f"{COREDHCP_CONFIG_PATH}"
        )
        comment_cmd = host.run(sed_comment)
        step2_ok = comment_cmd.rc == 0
        steps.append({
            "step": 2,
            "name": "Comment out single-subnet lines",
            "command": sed_comment,
            "success": step2_ok,
            "detail": "Single-subnet coresmd/bootloop lines commented out"
                      if step2_ok else comment_cmd.stderr.strip(),
        })
        if not step2_ok:
            return {
                "success": False,
                "steps": steps,
                "error": "Step 2 failed: could not comment out "
                         "single-subnet lines",
            }

        # ── Step 3: Uncomment multi-subnet coresmd and bootloop blocks ───
        # Remove the leading '# ' from all commented multi-subnet config
        # lines. Targets '    # - coresmd: |' through end of block,
        # and '    #     key=value' lines.
        sed_uncomment = (
            "sed -i '/^    # - coresmd: |/,/^$/{s/^    # /    /}' "
            f"{COREDHCP_CONFIG_PATH}"
        )
        uncomment_cmd = host.run(sed_uncomment)
        step3_ok = uncomment_cmd.rc == 0

        # Also uncomment bootloop block if it wasn't caught above
        sed_uncomment_bootloop = (
            "sed -i '/^    # - bootloop: |/,/^$/{s/^    # /    /}' "
            f"{COREDHCP_CONFIG_PATH}"
        )
        uncomment_boot_cmd = host.run(sed_uncomment_bootloop)
        step3_ok = step3_ok and uncomment_boot_cmd.rc == 0

        steps.append({
            "step": 3,
            "name": "Uncomment multi-subnet blocks",
            "command": sed_uncomment,
            "success": step3_ok,
            "detail": "Multi-subnet coresmd/bootloop blocks uncommented"
                      if step3_ok
                      else "Failed to uncomment multi-subnet blocks",
        })
        if not step3_ok:
            return {
                "success": False,
                "steps": steps,
                "error": "Step 3 failed: could not uncomment "
                         "multi-subnet blocks",
            }
    else:
        steps.append({
            "step": 2, "name": "Comment out single-subnet lines",
            "success": True, "detail": "Skipped (config already active)",
        })
        steps.append({
            "step": 3, "name": "Uncomment multi-subnet blocks",
            "success": True, "detail": "Skipped (config already active)",
        })

    # ── Step 4: Update coresmd image in quadlet container files ────────
    step4_ok = True
    step4_details = []
    for quadlet_file in (CORESMD_COREDHCP_CONTAINER_FILE,
                         CORESMD_COREDNS_CONTAINER_FILE):
        # Replace any coresmd image line with the target version
        sed_image = (
            f"sed -i 's|^Image=.*coresmd:.*|"
            f"Image={CORESMD_MULTISUBNET_IMAGE}|' {quadlet_file}"
        )
        img_cmd = host.run(sed_image)
        # Verify the image was actually updated
        verify_cmd = host.run(
            f"grep -q 'Image={CORESMD_MULTISUBNET_IMAGE}' {quadlet_file}"
        )
        if img_cmd.rc != 0 or verify_cmd.rc != 0:
            step4_ok = False
            actual = host.run(f"grep '^Image=' {quadlet_file}")
            step4_details.append(
                f"FAILED: {quadlet_file} "
                f"(current: {actual.stdout.strip()})"
            )
        else:
            step4_details.append(f"Updated: {quadlet_file}")

    steps.append({
        "step": 4,
        "name": "Update quadlet image references",
        "success": step4_ok,
        "detail": "; ".join(step4_details),
    })
    if not step4_ok:
        return {
            "success": False,
            "steps": steps,
            "error": "Step 4 failed: could not update quadlet container files",
        }

    # ── Step 5: Reload systemd daemon ──────────────────────────────────
    reload_cmd = host.run("systemctl daemon-reload")
    step5_ok = reload_cmd.rc == 0
    steps.append({
        "step": 5,
        "name": "Reload systemd daemon",
        "command": "systemctl daemon-reload",
        "success": step5_ok,
        "detail": "daemon-reload successful" if step5_ok
                  else reload_cmd.stderr.strip(),
    })
    if not step5_ok:
        return {
            "success": False,
            "steps": steps,
            "error": "Step 5 failed: systemctl daemon-reload",
        }

    # ── Step 6: Restart openchami.target ───────────────────────────────
    restart_cmd = host.run(f"systemctl restart {OPENCHAMI_TARGET}")
    step6_ok = restart_cmd.rc == 0
    steps.append({
        "step": 6,
        "name": "Restart openchami.target",
        "command": f"systemctl restart {OPENCHAMI_TARGET}",
        "success": step6_ok,
        "detail": "openchami.target restarted" if step6_ok
                  else restart_cmd.stderr.strip(),
    })

    return {
        "success": step6_ok,
        "steps": steps,
        "error": "" if step6_ok else "Step 6 failed: systemctl restart openchami.target",
    }


